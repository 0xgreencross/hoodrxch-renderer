const GLYPH_ID = {'#':'gH','/':'gS','.':'gD',':':'gC','-':'gM'};
function glyphId(ch){ return GLYPH_ID[ch] || ('g'+ch); }
// bitmap → path (runs per row, unit grid, relative commands)
function glyphPath(rows){
  let d='';
  for(let y=0;y<7;y++){ const r=rows[y]; let x=0;
    while(x<5){ if(r[x]==='1'){ let w=1; while(x+w<5&&r[x+w]==='1') w++; d+='M'+x+' '+y+'h'+w+'v1h-'+w+'z'; x+=w; } else x++; }
  }
  return d;
}
// Text placement. Returns {svg, used:Set}. size = pixels per cell. Advance 6 cells.
function text(str, x, y, size, fill, used){
  let s='';
  for(let i=0;i<str.length;i++){ const ch=str[i]; if(ch===' ') continue; if(!GLYPHS[ch]) continue;
    used.add(ch);
    s+='<use href="#'+glyphId(ch)+'" transform="translate('+(x+i*6*size)+' '+y+') scale('+size+')" fill="'+fill+'"/>';
  }
  return s;
}
function textWidth(str,size){ return (str.length*6-1)*size; }
function glyphDefs(used){ let s=''; for(const ch of used) s+='<path id="'+glyphId(ch)+'" d="'+glyphPath(GLYPHS[ch])+'"/>'; return s; }
